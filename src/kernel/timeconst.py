# Stand-in for kernel/time/timeconst.bc when bc is not installed.
# usage: timeconst.py <HZ> > include/generated/timeconst.h
import sys
from math import gcd
hz=int(sys.argv[1])
fmul=lambda b,n,d:(2**b*n+d-1)//d
def fadj(b,n,d):
    d=d//gcd(n,d); return 2**b*(d-1)//d
def fmuls(b,n,d):
    s=0
    while fmul(s,n,d) < 2**(b-1): s+=1
    return s
o=["/* Automatically generated by kernel/time/timeconst.bc */",f"/* Time conversion constants for HZ == {hz} */","",
"#ifndef KERNEL_TIMECONST_H","#define KERNEL_TIMECONST_H","","#include <linux/param.h>","#include <linux/types.h>","",
f"#if HZ != {hz}",'#error "include/generated/timeconst.h has the wrong HZ value!"',"#endif",""]
def blk(a,n,d):
    s=fmuls(32,n,d)
    o.extend([f"#define {a}_MUL32\tU64_C(0x{fmul(s,n,d):X})",f"#define {a}_ADJ32\tU64_C(0x{fadj(s,n,d):X})",f"#define {a}_SHR32\t{s}"])
blk("HZ_TO_MSEC",1000,hz); blk("MSEC_TO_HZ",hz,1000)
cd=gcd(hz,1000); o+= [f"#define HZ_TO_MSEC_NUM\t\t{1000//cd}",f"#define HZ_TO_MSEC_DEN\t\t{hz//cd}",f"#define MSEC_TO_HZ_NUM\t\t{hz//cd}",f"#define MSEC_TO_HZ_DEN\t\t{1000//cd}",""]
blk("HZ_TO_USEC",1000000,hz); blk("USEC_TO_HZ",hz,1000000)
cd=gcd(hz,10**6); o+= [f"#define HZ_TO_USEC_NUM\t\t{10**6//cd}",f"#define HZ_TO_USEC_DEN\t\t{hz//cd}",f"#define USEC_TO_HZ_NUM\t\t{hz//cd}",f"#define USEC_TO_HZ_DEN\t\t{10**6//cd}"]
cd=gcd(hz,10**9); o+= [f"#define HZ_TO_NSEC_NUM\t\t{10**9//cd}",f"#define HZ_TO_NSEC_DEN\t\t{hz//cd}",f"#define NSEC_TO_HZ_NUM\t\t{hz//cd}",f"#define NSEC_TO_HZ_DEN\t\t{10**9//cd}","","#endif /* KERNEL_TIMECONST_H */"]
print("\n".join(o))
